namespace age {

class ParameterTable;

enum class FeatureType { Sketch, Extrude, Revolve, Fillet, Chamfer, ImportStep };

const char* featureTypeName(FeatureType t);    // file format key: "import_step"
const char* featureDisplayName(FeatureType t); // default feature names: "Import"
std::optional<FeatureType> parseFeatureType(std::string_view name);

// A solid in the design. A body's id is the id of the feature that created
// it, which keeps ids stable across recomputes.
struct Body {
    int id = 0;
    std::string name;
    ShapePtr shape;
};

// Who made an edit: the person using the app, a script, or an agent.
enum class ActorKind { Person, Script, Agent };

inline constexpr auto kActorKinds = makeEnumTable<EnumName<ActorKind>>({
    {ActorKind::Person, "person"},
    {ActorKind::Script, "script"},
    {ActorKind::Agent, "agent"},
});
constexpr const auto& enumTable(ActorKind) { return kActorKinds; }

struct Actor {
    ActorKind kind = ActorKind::Person;
    std::string name; // the agent or script, e.g. "claude"; empty for the person

    bool operator==(const Actor&) const = default;
};

class Feature;

// Visits an expression string held by a feature; may rewrite it.
using ExpressionVisitor = std::function<void(std::string& source)>;

// State threaded through the timeline during a recompute.
struct RecomputeContext {
    Kernel& kernel;
    const ParameterTable& params;
    std::map<int, Body> bodies;
    int bodyCounter = 0; // for default body names

    const Feature* findFeature(int id) const;
    std::vector<const Feature*> executed; // features already run, in order
};

// One step in the parametric history (an entry on the timeline).
// Features hold only their definition; geometry is regenerated by execute().
class Feature {
public:
    virtual ~Feature() = default;

    virtual FeatureType type() const = 0;
    virtual std::unique_ptr<Feature> clone() const = 0;
    // Throws age::Error on failure; the document records the message and continues.
    virtual void execute(RecomputeContext& ctx) = 0;
    // Ids of features this one references (deleting those is refused).
    virtual std::vector<int> dependencies() const { return {}; }
    // Calls `fn` on every expression this feature evaluates, so references to
    // parameters can be found and renamed.
    virtual void visitExpressions(const ExpressionVisitor& fn) = 0;
    // Id of the body this feature creates or modifies, or -1 (sketches).
    virtual int outputBody() const { return -1; }

    int id = 0;
    std::string name;
    bool suppressed = false;
    Actor createdBy;  // who added the feature
    Actor modifiedBy; // who last changed its definition

    // Result of the last recompute.
    std::string error;
    bool healthy() const { return error.empty(); }

protected:
    Feature() = default;
    Feature(const Feature&) = default;
    Feature& operator=(const Feature&) = default;
};

// CRTP helper that implements type() and clone(). `Base` is Feature or an
// intermediate class shared by several feature types.
template <class Derived, FeatureType kType, class Base = Feature>
class FeatureBase : public Base {
public:
    static constexpr FeatureType kStaticType = kType;
    FeatureType type() const final { return kType; }
    std::unique_ptr<Feature> clone() const final {
        return std::make_unique<Derived>(static_cast<const Derived&>(*this));
    }

private:
    FeatureBase() = default; // only Derived may construct its base
    friend Derived;
};

template <class T>
T* featureCast(Feature* f) {
    return f && f->type() == T::kStaticType ? static_cast<T*>(f) : nullptr;
}
template <class T>
const T* featureCast(const Feature* f) {
    return f && f->type() == T::kStaticType ? static_cast<const T*>(f) : nullptr;
}

} // namespace age

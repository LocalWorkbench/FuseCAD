#pragma once

#include "oc/kernel/Kernel.h"

#include <map>
#include <memory>
#include <string>
#include <vector>

namespace oc {

class ParameterTable;

enum class FeatureType { Sketch, Extrude, Revolve, Fillet, Chamfer, ImportStep };

const char* featureTypeName(FeatureType t);
bool parseFeatureType(const std::string& name, FeatureType& out);

// A solid in the design. A body's id is the id of the feature that created
// it, which keeps ids stable across recomputes.
struct Body {
    int id = 0;
    std::string name;
    ShapePtr shape;
};

class Feature;

// State threaded through the timeline during a recompute.
struct RecomputeContext {
    Kernel& kernel;
    const ParameterTable& params;
    std::map<int, Body> bodies;
    int lastBody = -1;   // most recently created or modified body
    int bodyCounter = 0; // for default body names

    const Feature* findFeature(int id) const;
    std::vector<const Feature*> executed; // features already run, in order
};

// One step in the parametric history (an entry on the timeline).
// Features hold only their definition; geometry is regenerated by execute().
class Feature {
public:
    virtual ~Feature() = default;

    virtual FeatureType type() const = 0;
    virtual std::unique_ptr<Feature> clone() const = 0;
    // Throws oc::Error on failure; the document records the message and continues.
    virtual void execute(RecomputeContext& ctx) = 0;
    // Ids of features this one references (deleting those is refused).
    virtual std::vector<int> dependencies() const { return {}; }

    int id = 0;
    std::string name;
    bool suppressed = false;

    // Result of the last recompute.
    std::string error;
    bool healthy() const { return error.empty(); }

protected:
    Feature() = default;
    Feature(const Feature&) = default;
    Feature& operator=(const Feature&) = default;
};

// CRTP helper that implements type() and clone().
template <class Derived, FeatureType kType>
class FeatureBase : public Feature {
public:
    static constexpr FeatureType kStaticType = kType;
    FeatureType type() const final { return kType; }
    std::unique_ptr<Feature> clone() const final {
        return std::make_unique<Derived>(static_cast<const Derived&>(*this));
    }

private:
    FeatureBase() = default; // only Derived may construct its base
    friend Derived;
};

template <class T>
T* featureCast(Feature* f) {
    return f && f->type() == T::kStaticType ? static_cast<T*>(f) : nullptr;
}
template <class T>
const T* featureCast(const Feature* f) {
    return f && f->type() == T::kStaticType ? static_cast<const T*>(f) : nullptr;
}

} // namespace oc
